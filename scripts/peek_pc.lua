-- 멈춘 자리를 찾는다. PCSX-Redux 의 Lua Console 에 붙여 넣고 실행한다.
--
-- 게임이 무한 루프에 갇혀도 에뮬레이터는 계속 돈다. 그래서 그때의 PC 를 읽으면
-- 갇힌 자리가 바로 나온다.
--
-- **한 번에 여러 번 읽으려 하면 안 된다.** Lua 는 에뮬레이터와 같은 흐름에서
-- 도므로 루프를 돌리는 동안 게임은 한 발짝도 못 나간다. 4,000번을 읽어도 전부
-- 같은 값이 나온다. 그래서 이 파일은 **한 번만 읽고 끝낸다.** 콘솔에서 여러 번
-- 실행하면 실행 사이에 게임이 진행하므로 서로 다른 값이 나온다.
--
-- 쓰는 법
--   1. 아이템(또는 기술) 메뉴를 골라 멈춘 상태로 둔다
--   2. 이 내용을 Lua Console 에 붙여 넣고 실행한다
--   3. **예닐곱 번 더 실행한다** — 나온 주소들이 갇힌 구간이다
--   4. 나온 줄을 그대로 붙여 주면 된다

local r = PCSX.getRegisters()
local g = r.GPR.n

print(string.format('pc %08x   ra %08x   sp %08x',
    r.pc, g.ra, g.sp))
print(string.format('  a0 %08x  a1 %08x  a2 %08x  a3 %08x',
    g.a0, g.a1, g.a2, g.a3))
print(string.format('  v0 %08x  v1 %08x  s0 %08x  s1 %08x',
    g.v0, g.v1, g.s0, g.s1))
